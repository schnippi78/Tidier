def esc(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')

def main():
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    res = os.path.join(here, "Resources")
    missing = 0
    for code, table in T.items():
        d = os.path.join(res, f"{code}.lproj")
        os.makedirs(d, exist_ok=True)
        lines = ["/* Tidier — Localizable.strings (%s). Hand-authored. */" % code, ""]
        for k in KEYS:
            if k not in table:
                print(f"  ! MISSING {code}/{k}")
                missing += 1
                v = T["en"][k]
            else:
                v = table[k]
            lines.append(f'"{k}" = "{esc(v)}";')
        with open(os.path.join(d, "Localizable.strings"), "w", encoding="utf-8") as f:
            f.write("\n".join(lines) + "\n")
    print(f"Wrote {len(T)} languages, {len(KEYS)} keys each. Missing: {missing}")

if __name__ == "__main__":
    main()
